/**
 * `scripts/fake-seerr` for the tests on the tvOS simulator, on a port the system picks (a peer's
 * fake may hold 5056), started when the test task first asks and stopped when the build ends.
 * The simulator reaches the Mac at localhost.
 */
abstract class FakeSeerr : BuildService<FakeSeerr.Params>, AutoCloseable {
    interface Params : BuildServiceParameters {
        val script: RegularFileProperty
        val log: RegularFileProperty
    }

    private var process: Process? = null
    private var url: String? = null

    @Synchronized
    fun url(): String {
        url?.let { return it }
        val log = parameters.log.get().asFile.also { it.parentFile.mkdirs() }
        val started = ProcessBuilder("python3", parameters.script.get().asFile.path, "0").redirectError(log).start()
        process = started
        val line = started.inputStream.bufferedReader().readLine() ?: error("fake-seerr did not start: see $log")
        val port = Regex("""127\.0\.0\.1:(\d+)""").find(line)?.groupValues?.get(1) ?: error("no port in \"$line\"")
        return "http://localhost:$port".also { url = it }
    }

    override fun close() {
        process?.let {
            it.destroy()
            it.waitFor(5, TimeUnit.SECONDS)
        }
    }
}

val fakeSeerr = gradle.sharedServices.registerIfAbsent("hitherCoreFakeSeerr", FakeSeerr::class) {
    parameters.script.set(rootProject.layout.projectDirectory.file("scripts/fake-seerr"))
    parameters.log.set(layout.buildDirectory.file("fake-seerr-tvos-test.log"))
}

/**
 * Hither's own simulator (M7: `heerr-m7`, never another project's), booted for the tvOS tests when it
 * is not running, and left running for the next run. Not KGP's standalone spawn: that has no Keychain
 * (errSecNotAvailable), and the session lives there.
 */
abstract class TvosSimulator : BuildService<TvosSimulator.Params> {
    interface Params : BuildServiceParameters {
        val device: Property<String>
    }

    private fun simctl(vararg args: String): String {
        val process = ProcessBuilder("xcrun", "simctl", *args).redirectErrorStream(true).start()
        val out = process.inputStream.bufferedReader().readText()
        check(process.waitFor() == 0) { "xcrun simctl ${args.joinToString(" ")} failed: $out" }
        return out
    }

    @Synchronized
    fun boot() {
        val device = parameters.device.get()
        val line = simctl("list", "devices").lines().firstOrNull { it.trim().startsWith("$device (") || it.contains("($device)") }
            ?: error("no simulator named $device: ./verify creates it (scripts/tvos-simulator)")
        if (!line.contains("(Booted)")) simctl("boot", device)
        simctl("bootstatus", device)
    }
}

val simulatorName = providers.gradleProperty("hither.simulator").orElse("heerr-m7")

val tvosSimulator = gradle.sharedServices.registerIfAbsent("hitherTvosSimulator", TvosSimulator::class) {
    parameters.device.set(simulatorName)
}

tasks.withType<KotlinNativeSimulatorTest>().configureEach {
    device.set(simulatorName)
    standalone.set(false)
    usesService(fakeSeerr)
    usesService(tvosSimulator)
    inputs.file(rootProject.file("scripts/fake-seerr")).withPathSensitivity(PathSensitivity.RELATIVE)
    val fake = fakeSeerr
    val simulator = tvosSimulator
    doFirst {
        simulator.get().boot()
        // simctl hands the test process only variables named SIMCTL_CHILD_*, without the prefix.
        (this as KotlinNativeSimulatorTest).environment("SIMCTL_CHILD_HITHER_FAKE_SEERR", fake.get().url())
    }
}
