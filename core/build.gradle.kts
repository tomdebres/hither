/**
 * The fixtures in `src/commonTest/fixtures` written out as a Kotlin map, so the tests read
 * them the same way on the JVM and on the simulator (Kotlin/Native has no resources).
 */
abstract class FixtureSources : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val fixtures: DirectoryProperty

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun write() {
        val out = output.get().asFile.resolve("com/tomdebres/hither/core/FixtureFiles.kt")
        out.parentFile.mkdirs()
        val files = fixtures.get().asFile.listFiles { f -> f.name.endsWith(".json") }!!.sortedBy { it.name }
        val entries = files.joinToString("\n") { f ->
            val text = f.readText()
            // One JVM string constant holds 65,535 bytes; the recorded files are far under it.
            check(text.length < 30_000) { "${f.name} is too long for one string constant: split it" }
            "    \"${f.nameWithoutExtension}\" to \"${literal(text)}\","
        }
        out.writeText(
            "// Generated by core/build.gradle.kts (fixtureSources) from src/commonTest/fixtures. Do not edit.\n" +
                "package com.tomdebres.hither.core\n\n" +
                "internal val FIXTURE_FILES: Map<String, String> = mapOf(\n$entries\n)\n",
        )
    }

    private fun literal(text: String): String = buildString {
        for (c in text) {
            when {
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '$' -> append("\\$")
                c == '\n' -> append("\\n")
                c == '\r' -> append("\\r")
                c == '\t' -> append("\\t")
                c.code < 0x20 || c.code > 0x7e -> append("\\u%04x".format(c.code))
                else -> append(c)
            }
        }
    }
}

